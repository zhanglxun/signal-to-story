/**
 * Build a single-transaction SQL release that brings the live database from its last applied migration
 * to the repo head (docs/database.md §8.1). The script is generated from the migration files, so the SQL
 * that the tests rehearse is exactly the SQL that runs live.
 *
 *   npx tsx testing/db/release.ts            → supabase/release/0.5.0-step{1,2,3}.sql
 *
 * Shape: preflight assertions → [retire legacy live-only objects] → pending migrations in order →
 * migration history rows → [V1 backfill (idempotent)] → commit. Any failure rolls everything back.
 * Bracketed sections are per batch (DB-D14): step 1 has both, step 2 neither.
 * The script contains no secrets and no project identifiers.
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

import { listMigrationFiles, MIGRATIONS_DIR, REPO_ROOT } from "./pglite-harness"

/** Last version recorded in the live migration history (DB0, supabase/snippets/migrations.json). */
export const LIVE_HEAD = "20261030023526"

/** Empty legacy reader-site tables that exist only live and clash with the repo's site_* tables (database.md §1.2). */
const LEGACY_SITE_TABLES = [
  "site_bookmarks", "site_categories", "site_entries", "site_entry_bodies", "site_release_events",
  "site_release_sources", "site_resources", "site_settings", "site_topic_items", "site_topics",
]
const LEGACY_FUNCTIONS: [schema: string, name: string][] = [
  ["public", "ensure_site_settings"], ["public", "publish_site_entry"], ["public", "unpublish_site_entry"],
  ["private", "is_verified_reader"], ["private", "site_entries_guard_release_fields"],
  ["public", "ingest_harvested_signals"],
]

const versionOf = (file: string) => file.slice(0, 14)
const nameOf = (file: string) => file.slice(15).replace(/\.sql$/, "")

export function pendingMigrations(after = LIVE_HEAD, upTo?: string): string[] {
  return listMigrationFiles().filter((f) => versionOf(f) > after && (!upTo || versionOf(f) <= upTo))
}

export interface ReleaseSpec {
  /** Last migration the live database has applied. */
  after: string
  /** Last migration this batch includes (default: repo head). */
  upTo?: string
  label: string
  file: string
  /** Drop the empty legacy live-only site_* objects (step 1 only). */
  retireLegacySite: boolean
  /** Run private.backfill_v1() after the migrations (step 1 only). */
  backfillV1: boolean
  /** SQL condition that is true when this batch was already applied (extra guard next to the history check). */
  appliedWhen: string
  /** Extra preflight statements (plpgsql, inside the preflight block). */
  preflight?: string[]
}

/** The batches pushed live, in order (DB-D14). A shipped batch is regenerated byte-identical. */
export const RELEASES = {
  step1: {
    after: LIVE_HEAD,
    upTo: "20261122100000",
    label: "0.5.0 step 1 (DB2a + DB2b)",
    file: "0.5.0-step1.sql",
    retireLegacySite: true,
    backfillV1: true,
    appliedWhen: "to_regclass('public.work_items') is not null or to_regclass('public.intake_events') is not null",
  },
  step2: {
    after: "20261122100000",
    upTo: "20261123100000",
    label: "0.5.0 step 2 (DB2c-1)",
    file: "0.5.0-step2.sql",
    retireLegacySite: false,
    backfillV1: false,
    appliedWhen: "exists (select 1 from information_schema.columns where table_schema = 'public' and table_name = 'agent_jobs' and column_name = 'lease_epoch')",
    preflight: [
      `  -- Workers must be stopped: a live lease would be cut off mid-write by the new RPC signatures.`,
      `  select count(*) into n from public.agent_jobs where status = 'running' and locked_until > now();`,
      `  if n > 0 then raise exception 'preflight: % agent job(s) hold a live lease; stop every worker and wait for the leases to expire', n; end if;`,
    ],
  },
  step3: {
    after: "20261123100000",
    label: "0.5.0 step 3 (DB2c-2)",
    file: "0.5.0-step3.sql",
    retireLegacySite: false,
    backfillV1: false,
    // Additive: the service_role node RPCs stay, so a running old-style worker is not cut off mid-job.
    appliedWhen: "to_regclass('public.runner_nodes') is not null",
  },
} satisfies Record<string, ReleaseSpec>

const sqlList = (xs: string[]) => xs.map((x) => `'${x.replace(/'/g, "''")}'`).join(", ")

export function buildRelease(r: ReleaseSpec): string {
  const after = r.after
  const files = pendingMigrations(after, r.upTo)
  if (!files.length) throw new Error(`no migrations after ${after}`)
  let section = 1
  const next = () => ++section
  const out: string[] = []
  out.push(
    `-- Signal to Story release: ${r.label}`,
    `-- Generated by testing/db/release.ts from supabase/migrations — do not edit by hand.`,
    `-- Brings the database from migration ${after} to ${versionOf(files.at(-1)!)} (${files.length} migration${files.length === 1 ? "" : "s"}) in ONE transaction.`,
    `-- Run it once, in the Supabase SQL editor or psql, AFTER taking a backup. Any error rolls everything back.`,
    ``,
    `begin;`,
    ``,
    `-- ── 1. Preflight: refuse to run on a database that is not in the expected state ──`,
    `do $preflight$`,
    `declare n bigint; t text;`,
    `begin`,
    `  if to_regclass('supabase_migrations.schema_migrations') is null then`,
    `    raise exception 'preflight: supabase_migrations.schema_migrations is missing';`,
    `  end if;`,
    `  select max(version) into t from supabase_migrations.schema_migrations;`,
    `  if t is distinct from '${after}' then`,
    `    raise exception 'preflight: expected last applied migration ${after}, found %', t;`,
    `  end if;`,
    `  if ${r.appliedWhen} then`,
    `    raise exception 'preflight: ${r.retireLegacySite ? "0.5 tables already exist" : "the objects of this batch already exist"} — this release was applied before';`,
    `  end if;`,
    ...(r.retireLegacySite
      ? [
          `  foreach t in array array[${sqlList(LEGACY_SITE_TABLES)}] loop`,
          `    if to_regclass('public.' || t) is not null then`,
          `      execute format('select count(*) from public.%I', t) into n;`,
          `      if n > 0 then raise exception 'preflight: legacy table public.% has % rows; it must be empty before it is dropped', t, n; end if;`,
          `    end if;`,
          `  end loop;`,
        ]
      : []),
    ...(r.preflight ?? []),
    `end $preflight$;`,
    ``
  )
  if (r.retireLegacySite) {
    out.push(
      `-- ── ${next()}. Retire legacy live-only objects (empty; database.md §1.2, DB-D3 / DB-D10 / DB-D12) ──`,
      ...LEGACY_SITE_TABLES.map((t) => `drop table if exists public.${t} cascade;`),
      `do $retire$`,
      `declare f record;`,
      `begin`,
      `  for f in select p.oid::regprocedure as sig from pg_proc p join pg_namespace n on n.oid = p.pronamespace`,
      `           where (n.nspname, p.proname) in (${LEGACY_FUNCTIONS.map(([s, n]) => `('${s}', '${n}')`).join(", ")}) loop`,
      `    execute format('drop function %s cascade', f.sig);`,
      `  end loop;`,
      `end $retire$;`,
      ``
    )
  }
  out.push(`-- ── ${next()}. Pending migrations, in order ──`)
  for (const file of files) {
    const body = readFileSync(path.join(MIGRATIONS_DIR, file), "utf8").trimEnd()
    out.push(``, `-- >>> ${file}`, body, `-- <<< ${file}`)
  }
  out.push(
    ``,
    `-- ── ${next()}. Migration history, so later \`supabase db push\` runs see these as applied ──`,
    `insert into supabase_migrations.schema_migrations (version, name) values`,
    files.map((f) => `  ('${versionOf(f)}', '${nameOf(f)}')`).join(",\n") + `;`,
    ``
  )
  if (r.backfillV1) {
    out.push(
      `-- ── ${next()}. Copy V1 rows into the 0.5 tables (idempotent; V1 tables are kept until the retire release) ──`,
      `do $backfill$`,
      `declare r jsonb;`,
      `begin`,
      `  r := private.backfill_v1();`,
      `  raise notice 'backfill_v1: %', r;`,
      `end $backfill$;`,
      ``
    )
  }
  out.push(`commit;`, ``)
  return out.join("\n")
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
if (isMain) {
  for (const spec of Object.values(RELEASES) as ReleaseSpec[]) {
    const out = path.join(REPO_ROOT, "supabase/release", spec.file)
    mkdirSync(path.dirname(out), { recursive: true })
    writeFileSync(out, buildRelease(spec))
    console.log(`wrote ${path.relative(REPO_ROOT, out)} (${pendingMigrations(spec.after, spec.upTo).length} migrations after ${spec.after})`)
  }
}
