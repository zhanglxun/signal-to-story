import { readdirSync, readFileSync, statSync } from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

import type { KnowledgeEntry } from "../src/contracts/knowledge-base"
import { importMarkdownToKnowledgeEntry } from "../src/lib/knowledge-markdown"

const here = path.dirname(fileURLToPath(import.meta.url))
export const CONSOLE_ROOT = path.resolve(here, "..")
export const REPO_ROOT = path.resolve(CONSOLE_ROOT, "..")
export const KNOWLEDGE_DIR = path.join(REPO_ROOT, "knowledge-base")
export const GENERATED_TS = path.join(CONSOLE_ROOT, "src/data/knowledge-base-defaults.generated.ts")

function walk(dir: string): string[] {
  return readdirSync(dir)
    .sort()
    .flatMap((name) => {
      const full = path.join(dir, name)
      if (statSync(full).isDirectory()) return walk(full)
      return name.endsWith(".md") && name.toLowerCase() !== "readme.md" ? [full] : []
    })
}

/** Parse every knowledge-base/**\/*.md (except README) as a trusted default entry. */
export function loadRepositoryKnowledge(dir = KNOWLEDGE_DIR): KnowledgeEntry[] {
  return walk(dir).map((file) => {
    const fallback = path.basename(file, ".md")
    const { entry } = importMarkdownToKnowledgeEntry(readFileSync(file, "utf8"), fallback)
    return { ...entry, trustLevel: "trusted", sourcePath: path.relative(REPO_ROOT, file).split(path.sep).join("/") }
  })
}

export function renderGeneratedTs(entries: KnowledgeEntry[]): string {
  return [
    "// GENERATED by `npm run kb:seed` from knowledge-base/*.md — do not edit by hand.",
    'import type { KnowledgeEntry } from "@/contracts/knowledge-base"',
    "",
    `export const DEFAULT_KNOWLEDGE_ENTRIES: readonly KnowledgeEntry[] = ${JSON.stringify(entries, null, 2)}`,
    "",
  ].join("\n")
}
