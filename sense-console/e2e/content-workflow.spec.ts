import { readFileSync } from 'node:fs'
import { expect, test } from '@playwright/test'

test.use({ actionTimeout: 15000 })
const fixturePath = process.env.CONTENT_E2E_FIXTURE
// Explicit disposable account only. Never use a personal production session.
test('cloud content: author, review, record the external publication link, re-review after edits', async ({ page }) => {
  test.skip(!fixturePath, 'Set CONTENT_E2E_FIXTURE to a disposable test account JSON')
  test.setTimeout(120000)
  const fixture = JSON.parse(readFileSync(fixturePath!, 'utf8')) as { email: string; password: string }
  await page.goto('/login')
  await page.locator('#email').fill(fixture.email)
  await page.locator('#password').fill(fixture.password)
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page).toHaveURL(/dashboard/, { timeout: 20000 })
  await page.goto('/work-items')
  await page.getByRole('button', { name: '新建事项' }).click()
  await page.getByLabel('标题').fill('验收：企业 AI 内容流程')
  await page.getByLabel('Brief').fill('解释企业 AI 如何从试验走向生产。引用需要人工核实。')
  await page.getByRole('button', { name: '创建事项' }).click()
  await expect(page).toHaveURL(/work-items\//)
  const itemUrl = page.url()
  await page.getByRole('button', { name: '创建母稿' }).click()
  await page.getByLabel('正文（Markdown）').fill('## 核心观点\n企业 AI 项目需要明确的流程、责任与验收。\n\n[待核实] 补充真实案例。')
  await page.getByRole('button', { name: '保存新版本' }).click()
  await expect(page.getByText('有未保存修改')).toHaveCount(0)
  await page.getByRole('button', { name: '提交审核', exact: true }).click()
  await page.getByRole('button', { name: '审核通过', exact: true }).click()
  await expect(page.getByText('已通过', { exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByTestId('markdown-preview')).toContainText(/企业 AI 项目/)
  await page.getByRole('button', { name: '添加平台版本' }).click()
  await page.getByRole('menuitem', { name: 'X' }).click()
  await page.getByRole('button', { name: '提交审核', exact: true }).click()
  await page.getByRole('button', { name: '审核通过', exact: true }).click()
  await expect(page.getByText('已通过', { exact: true })).toBeVisible()
  // Manual publishing elsewhere: record the external link on the approved X version (no channels / plans / metrics tables).
  await page.getByLabel('外部平台发布链接（人工发布后回填）').fill('https://example.com/spark-acceptance')
  await page.getByRole('button', { name: '保存链接' }).click()
  await page.goto('/analytics')
  await expect(page.getByRole('link', { name: 'https://example.com/spark-acceptance' })).toBeVisible()
  await page.screenshot({ path: '/tmp/spark-content-analytics.png', fullPage: true })
  await page.goto(itemUrl)
  await page.getByRole('button', { name: /X/ }).click()
  await page.getByRole('tab', { name: '编辑原文' }).click()
  await page.getByLabel('正文（Markdown）').fill('改稿后的版本需要重新审核。')
  await page.getByRole('button', { name: '保存新版本' }).click()
  await expect(page.getByRole('button', { name: '提交审核', exact: true })).toBeVisible()
  await page.screenshot({ path: '/tmp/spark-content-editor.png', fullPage: true })
})
